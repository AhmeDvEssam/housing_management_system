#!/bin/bash
echo "===================================================="
echo "    تجهيز النظام للعمل على لينكس (للتجربة فوراً)    "
echo "===================================================="

if [ ! -d ".venv" ]; then
    echo "[1/4] جاري إنشاء بيئة بايثون الافتراضية..."
    python3 -m venv .venv
else
    echo "[1/4] البيئة موجودة مسبقاً."
fi

echo "[2/4] جاري تفعيل البيئة وتثبيت المكتبات المطلوبة..."
source .venv/bin/activate
pip install -r requirements.txt

echo "[3/4] جاري تجهيز قاعدة البيانات وتطبيق التحديثات..."
cd backend
python3 manage.py migrate

echo "[4/4] جاري تجميع ملفات التصميم (Static Files)..."
python3 manage.py collectstatic --noinput

echo "===================================================="
echo "تم التجهيز بنجاح! شغل run_linux.sh الآن."
echo "===================================================="
